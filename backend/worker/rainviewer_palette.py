def _build():
    acc: dict[int, list[int]] = {}
    for dbz, rgba in RAIN + SNOW:
        if rgba & 0xFF == 0:  # transparent = no echo
            continue
        acc.setdefault(rgba, []).append(dbz)
    keys = np.array(sorted(acc), dtype=np.uint32)
    vals = np.array([float(np.mean(acc[int(k)])) for k in keys], dtype=np.float32)
    return keys, vals


KEYS, VALS = _build()
SNOW_KEYS = np.array(sorted({rgba for _, rgba in SNOW if rgba & 0xFF}), dtype=np.uint32)
_RGB = np.stack([(KEYS >> 24) & 255, (KEYS >> 16) & 255, (KEYS >> 8) & 255], axis=1).astype(np.int32)


def decode(rgba: np.ndarray) -> np.ndarray:
    """(H, W, 4) uint8 tile -> (H, W) float32 dBZ; NaN where transparent (no echo / no coverage)."""
    return decode_with_snow(rgba)[0]


def decode_with_snow(rgba: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Like decode(), plus a boolean mask of pixels drawn with the snow palette (tiles requested with snow=1)."""
    h, w, _ = rgba.shape
    flat = rgba.reshape(-1, 4).astype(np.uint32)
    packed = (flat[:, 0] << 24) | (flat[:, 1] << 16) | (flat[:, 2] << 8) | flat[:, 3]
    out = np.full(packed.shape, np.nan, dtype=np.float32)
    opaque = flat[:, 3] > 0
    uniq, inv = np.unique(packed[opaque], return_inverse=True)
    idx = np.searchsorted(KEYS, uniq)
    idx_c = np.clip(idx, 0, len(KEYS) - 1)
    exact = KEYS[idx_c] == uniq
    lut = np.where(exact, VALS[idx_c], np.nan).astype(np.float32)
    if (~exact).any():  # antialiased/unknown colours -> nearest palette colour (RGB distance)
        miss = np.where(~exact)[0]
        rgb = np.stack([(uniq[miss] >> 24) & 255, (uniq[miss] >> 16) & 255, (uniq[miss] >> 8) & 255], axis=1).astype(np.int32)
        d = ((rgb[:, None, :] - _RGB[None, :, :]) ** 2).sum(-1)
        lut[miss] = VALS[d.argmin(1)]
    out[opaque] = lut[inv]
    snow = np.zeros(packed.shape, dtype=bool)
    snow[opaque] = np.isin(uniq, SNOW_KEYS)[inv]
    return out.reshape(h, w), snow.reshape(h, w)
